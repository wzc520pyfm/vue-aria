import {computed, defineComponent, h, inject, provide, ref, watchEffect, type PropType} from 'vue'
import {mergeProps, toHeroDataAttrs, useSelectable} from 'vue-aria'
import {useOption} from 'vue-aria/useListBox'
import type {Key} from 'vue-stately/useListState'
import {ListBoxItemContextKey, ListStateContextKey} from './context'

export interface ListBoxItemProps {
  id?: Key
  textValue?: string
  isDisabled?: boolean
  shouldSelectOnPressUp?: boolean
  shouldFocusOnHover?: boolean
  value?: unknown
  href?: string
  'aria-label'?: string
}

export const ListBoxItem = defineComponent({
  name: 'ListBoxItem',
  inheritAttrs: false,
  props: {
    id: {type: null as unknown as PropType<Key | undefined>, default: undefined},
    textValue: {type: String, default: undefined},
    isDisabled: {type: Boolean, default: false},
    shouldSelectOnPressUp: {type: Boolean, default: undefined},
    shouldFocusOnHover: {type: Boolean, default: undefined},
    value: {type: null, default: undefined},
    href: {type: String, default: undefined},
    'aria-label': {type: String, default: undefined},
  },
  emits: ['press', 'pressstart', 'pressend', 'pressup', 'action'],
  setup(props, {slots, attrs, emit}) {
    const state = inject(ListStateContextKey, null)
    if (!state) {
      throw new Error('ListBoxItem must be used within a ListBox')
    }
    const itemRef = ref<HTMLElement | null>(null)

    // key resolution: prefer explicit id, else try injected context from dynamic rendering? 
    // For static, id prop required for stable key unless generated by builder (builder sets data-key?). 
    // We'll expect id/key to be passed as prop `id` by our builder/renderer.
    const itemKey = computed<Key>(() => (props.id ?? null) as Key)

    const {optionProps, labelProps, descriptionProps, isFocused, isFocusVisible, isSelected, isDisabled, isPressed, isHovered, allowsSelection, hasAction} = useOption(
      {
        key: itemKey,
        isDisabled: () => props.isDisabled,
        'aria-label': () => props['aria-label'],
        shouldSelectOnPressUp: () => props.shouldSelectOnPressUp,
        shouldFocusOnHover: () => props.shouldFocusOnHover,
      },
      state as any,
      itemRef as any,
    )

    provide(ListBoxItemContextKey, {labelProps, descriptionProps})

    const {selectedAttrs} = useSelectable({isSelected: () => isSelected.value})

    const domProps = computed(() => {
      const base = mergeProps(optionProps, attrs)
      const dataAttrs = {
        ...toHeroDataAttrs({
          hovered: isHovered.value,
          focused: isFocused.value,
          focusVisible: isFocusVisible.value,
          disabled: isDisabled.value,
          pressed: isPressed.value,
        }),
        ...selectedAttrs.value,
      }
      if (state.selectionManager.selectionMode !== 'none') {
        ;(dataAttrs as any)['data-selection-mode'] = state.selectionManager.selectionMode
      }
      return {...base, ...dataAttrs, ref: (el: any) => { itemRef.value = el as HTMLElement }}
    })

    // focus element when manager focuses this key
    watchEffect(() => {
      if (isFocused.value && itemRef.value && document.activeElement !== itemRef.value) {
        itemRef.value.focus?.()
      }
    })

    return () => h('div', domProps.value, slots.default?.())
  },
})
